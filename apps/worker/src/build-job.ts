import type { Job } from "bullmq";
import { runCodingAgent } from "@readycheck/ai";
import { getPrismaClient } from "@readycheck/db";
import { slugify } from "@readycheck/github";
import { getBuildQueue, type BuildJobData } from "@readycheck/queue";
import { analyze } from "./analyze";
import { checkout, JobError, openPullRequest, stageAndDiff } from "./checkout";

const prisma = getPrismaClient();

const TEST_FILE = /(\.|_)(test|spec)\.[a-z]+$|(^|\/)(__tests__|tests?)\//i;

const BUILD_GUIDANCE = `You are building one feature slice of a larger app. Build exactly this slice's stories, nothing from later slices.
Write automated tests for every story, in the test framework the repository already uses (set one up if there is none).
If the repository is empty or nearly empty, scaffold the app with the stack named in the spec, keeping it minimal.
Don't add secrets or real credentials; read configuration from environment variables and document new ones in .env.example.`;

function task(slice: { title: string; stories: string[]; spec: string; position: number }): string {
  return `Project spec (from the approved Blueprint):
${slice.spec}

Slice ${slice.position}: ${slice.title}
Stories:
${slice.stories.map((s) => `- ${s}`).join("\n")}

Implement this slice in the repository.`;
}

/** Starts the next queued slice of the project, if any. Slices build one at a time, in order. */
export async function startNextSlice(projectId: string): Promise<void> {
  const busy = await prisma.buildSlice.count({ where: { projectId, status: "generating" } });
  if (busy > 0) return;
  const next = await prisma.buildSlice.findFirst({
    where: { projectId, status: "queued" },
    orderBy: { position: "asc" },
  });
  if (next) await getBuildQueue().add("build-slice", { sliceId: next.id }, { jobId: `slice-${next.id}-${Date.now()}` });
}

export async function processSlice(job: Job<BuildJobData>): Promise<void> {
  const slice = await prisma.buildSlice.update({
    where: { id: job.data.sliceId },
    data: { status: "generating", error: null },
    include: { project: true },
  });
  if (!slice.project.repoPath) throw new JobError("Connect the project's repository before building.");
  if (!process.env.ANTHROPIC_API_KEY) {
    throw new JobError("Building slices needs the AI builder (ANTHROPIC_API_KEY on the worker).");
  }
  const org = await prisma.organization.findUnique({ where: { id: slice.orgId }, select: { disabledRules: true } });

  const branch = `readycheck/slice-${slice.position}-${slugify(slice.title, 32)}`;
  const co = await checkout(slice.orgId, slice.project.repoPath, branch);
  try {
    const before = analyze(co.dir, org?.disabledRules).issues.map((i) => i.ruleId);
    const result = await runCodingAgent({ root: co.dir, task: task(slice), guidance: BUILD_GUIDANCE, maxTurns: 60 });
    const { files } = await stageAndDiff(co);
    if (files.length === 0) throw new JobError(`The builder made no changes. ${result.summary}`);

    // Pre-review: findings this branch adds compared with the default branch.
    const after = analyze(co.dir, org?.disabledRules).issues;
    const introduced = after
      .filter((i) => !before.includes(i.ruleId))
      .map((i) => ({ ruleId: i.ruleId, severity: i.severity, message: i.message }));
    const testsAdded = files.filter((f) => TEST_FILE.test(f)).length;

    const body = `Slice ${slice.position} of **${slice.project.name}**, built by ReadyCheck from the approved Blueprint.

### Stories
${slice.stories.map((s) => `- [ ] ${s}`).join("\n")}

### What changed
${result.summary}

### Pre-review
- Test files added or changed: ${testsAdded}
- New readiness findings: ${introduced.length ? introduced.map((i) => `${i.ruleId} (${i.severity})`).join(", ") : "none"}

This code was written by an AI model. Review it like any other pull request; nothing reaches \`${co.baseBranch}\` until you merge.
`;
    const pr = await openPullRequest(co, {
      title: `Slice ${slice.position}: ${slice.title}`,
      body,
      commitMessage: `Add ${slice.title}\n\nGenerated by ReadyCheck.`,
    });

    await prisma.buildSlice.update({
      where: { id: slice.id },
      data: {
        status: "review",
        branch,
        prNumber: pr.number,
        prUrl: pr.url,
        summary: result.summary,
        testsAdded,
        issuesFound: introduced,
      },
    });
  } finally {
    co.cleanup();
  }
  await startNextSlice(slice.projectId);
}
